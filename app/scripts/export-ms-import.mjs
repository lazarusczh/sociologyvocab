// ms-data.json -> ms-import.sql（INSERT ... ON CONFLICT (session,comp,q) DO UPDATE，幂等）
// 用法：node scripts/export-ms-import.mjs && psql "<conn>" -f ms-import.sql
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..', '..');
const msData = JSON.parse(readFileSync(join(ROOT, 'ms-data.json'), 'utf8'));
const esc = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = ['-- auto-generated by app/scripts/export-ms-import.mjs', 'BEGIN;'];
let n = 0;
for (const m of msData) {
  const paper = Number(m.comp[0]);
  for (const s of m.sections) {
    lines.push(
      `INSERT INTO public.ms_sections (session, comp, paper, q, text) VALUES (${esc(m.session)}, ${esc(m.comp)}, ${paper}, ${esc(s.q)}, ${esc(s.text)}) ` +
      `ON CONFLICT (session, comp, q) DO UPDATE SET paper=EXCLUDED.paper, text=EXCLUDED.text, updated_at=now();`
    );
    n++;
  }
}
lines.push('COMMIT;');
const out = join(ROOT, 'ms-import.sql');
writeFileSync(out, lines.join('\n'));
console.log('volumes:', msData.length, 'sections:', n, '->', out);
