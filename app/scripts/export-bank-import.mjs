// question-bank.json -> question-bank-import.sql（INSERT ... ON CONFLICT (qid) DO UPDATE，幂等）
// 用法：node scripts/export-bank-import.mjs && psql "<conn>" -f question-bank-import.sql
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, '..', '..');
const bank = JSON.parse(readFileSync(join(ROOT, 'question-bank.json'), 'utf8'));
const esc = (s) => (s == null ? null : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a && a.length ? `array[${a.map((x) => esc(x)).join(',')}]` : `'{}'::text[]`);

const lines = ['-- auto-generated by app/scripts/export-bank-import.mjs', 'BEGIN;'];
for (const it of bank) {
  const s = it.source;
  const parts = it.parts ? `'${JSON.stringify(it.parts).replace(/'/g, "''")}'::jsonb` : 'NULL';
  lines.push(
    `INSERT INTO public.question_bank (qid, session, paper, variant, comp, q, stem, statement, marks, marks_total, kind, parts, topics) VALUES (` +
      `${esc(it.qid)}, ${esc(s.session)}, ${s.paper}, ${s.variant}, ${esc(s.comp)}, ${esc(s.q)}, ${esc(it.stem)}, ` +
      `${esc(it.statement)}, ${esc(it.marks)}, ${it.marksTotal}, ${esc(it.kind)}, ${parts}, ${arr(it.topics)}) ` +
      `ON CONFLICT (qid) DO UPDATE SET session=EXCLUDED.session, paper=EXCLUDED.paper, variant=EXCLUDED.variant, ` +
      `comp=EXCLUDED.comp, q=EXCLUDED.q, stem=EXCLUDED.stem, statement=EXCLUDED.statement, marks=EXCLUDED.marks, ` +
      `marks_total=EXCLUDED.marks_total, kind=EXCLUDED.kind, parts=EXCLUDED.parts, topics=EXCLUDED.topics, updated_at=now();`
  );
}
lines.push('COMMIT;');
const out = join(ROOT, 'question-bank-import.sql');
writeFileSync(out, lines.join('\n'));
console.log('rows:', bank.length, '->', out);
