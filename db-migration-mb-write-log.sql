-- ============================================================================
-- mb_write_log：「上次把哪些分数登进了 ManageBac」的快照
--
-- 用法（本机 psql 免交互）：
--   $env:PGPASSFILE="$env:USERPROFILE\.pgpass"
--   psql $conn -w -v ON_ERROR_STOP=1 -f db-migration-mb-write-log.sql
--
-- 幂等，可重复执行。
--
-- ---------------------------------------------------------------------------
-- 为什么需要这张表
--
-- 教师改了分（学生订正 / 学生用加分卡）⇒ 站内最终分变了，但 ManageBac 上
-- 还是旧分 ⇒ 需要提醒教师「这份卷要重新登分」。
--
-- 判断「变了之后有没有重新登过」需要知道**上次登的是什么分**。而现状是：
--   · `writeMbMarks`（app/src/lib/cloud.ts）写完就返回，不落任何流水；
--   · `mb_task_links` 只有 `bound_at`（绑定时刻），不是登分时刻。
-- ⇒ 没有快照就只能每次实时抓 ManageBac 才知道要不要登分，而抓一次消耗
--   CF 浏览器额度（约 8~15 秒/次，免费额度 10 分钟/天）。
-- 有了本表，判定变成纯站内计算，**零浏览器额度**。
--
-- ---------------------------------------------------------------------------
-- 两个设计要点
--
-- ① `scores` 的键是 **user_id**，不是 ManageBac 显示名。
--    写 ManageBac 时按显示名定位行，但站内比对用显示名会因改名而错位。
--
-- ② `scores` **只记实际写进去的行**。
--    教师可以只勾部分行写入（QuizManager 的 `todo = lines.filter(l => l.checked ...)`）；
--    若把未写的行也记成快照，那些行会被误判成「已登分」。
--
-- ⚠ 本表不参与 ManageBac 写入本身，纯记录；写入失败的步骤不受影响。
-- ============================================================================

create table if not exists public.mb_write_log (
  id          bigint generated by default as identity primary key,
  quiz_id     uuid not null references public.quizzes(id) on delete cascade,
  class_id    uuid references public.classes(id) on delete cascade,
  mb_task_id  text not null,                    -- 写进了哪个 task（同一作业发两班 = 两条记录）
  -- 写入时刻的分数快照：{ "<user_id>": "<写入的分数>" }
  scores      jsonb not null default '{}'::jsonb,
  -- 'auto'   = 站内「写入 ManageBac」按钮
  -- 'manual' = 教师点「我已手动登分」（油猴脚本 / 手工填分那条兜底路径）
  source      text not null default 'auto' check (source in ('auto', 'manual')),
  written_by  uuid,
  written_at  timestamptz not null default now()
);

-- ⚠ 用普通索引：本库为 AnalyticDB / Greenplum 内核，部分索引/表达式索引的支持不确定
--   （与 db-migration-mb-sync.sql 头部同一条约定）
create index if not exists mb_write_log_quiz_idx
  on public.mb_write_log (quiz_id, written_at);

-- ============================================================================
-- 行级安全：仅 teacher / developer 可读写（照 db-migration-mb-sync-2.sql 同款）
-- 学生端完全没有这条链路的入口，故不需要任何 select 策略。
-- ============================================================================
alter table public.mb_write_log enable row level security;

drop policy if exists "mb_write_log_teacher" on public.mb_write_log;
create policy "mb_write_log_teacher" on public.mb_write_log
  for all
  using (exists (
    select 1 from public.user_roles r
    where r.user_id = auth.uid() and r.role in ('teacher', 'developer')
  ))
  with check (exists (
    select 1 from public.user_roles r
    where r.user_id = auth.uid() and r.role in ('teacher', 'developer')
  ));

comment on table public.mb_write_log is
  'ManageBac 登分快照：每次写入（或教师标记「已手动登分」）记一行，'
  'scores 为 {user_id: 写入的分数}，只含实际写进去的行。'
  '用途：判断站内最终分变了之后有没有重新登分（纯站内计算，不抓 ManageBac）。';

-- ============================================================================
-- 复核
-- ============================================================================
\echo '== 1) 表已建（应有一行）=='
select c.relname, c.relrowsecurity as rls_enabled
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relname = 'mb_write_log';

\echo ''
\echo '== 2) RLS 策略（应只有 mb_write_log_teacher 一条）=='
select policyname, cmd
  from pg_policies
 where schemaname = 'public' and tablename = 'mb_write_log';

\echo ''
\echo '== 3) 现状（新表应为 0 行）=='
select 'mb_write_log' as obj, count(*)::text as rows from public.mb_write_log;
