-- ============================================================================
-- ⑤ get_card_balance()：余额出口（**先补发，再现算**）
-- ============================================================================
create or replace function public.get_card_balance()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := auth.uid();
  v_makeup integer;
  v_bonus  integer;
begin
  if v_uid is null then
    raise exception 'not authenticated';
  end if;

  perform public.grant_pending_cards(v_uid);

  -- 补签卡：发放流水 − checkin_makeups（每条补签就是一次使用）
  select count(*) into v_makeup
    from public.card_grants g
   where g.user_id = v_uid and g.kind = 'makeup';
  v_makeup := v_makeup - (select count(*) from public.checkin_makeups m where m.user_id = v_uid);

  -- 加分卡：发放流水 − 使用流水
  select count(*) into v_bonus
    from public.card_grants g
   where g.user_id = v_uid and g.kind = 'bonus';
  v_bonus := v_bonus - (select count(*) from public.card_uses u
                         where u.user_id = v_uid and u.kind = 'bonus');

  return jsonb_build_object(
    'makeup', greatest(0, v_makeup),
    'bonus',  greatest(0, v_bonus)
  );
end $$;

grant execute on function public.get_card_balance() to authenticated;

comment on function public.get_card_balance() is
  '补签卡/加分卡余额。读时先补发欠的卡，再按「发放 − 使用」现算。学生只需自己的。';
